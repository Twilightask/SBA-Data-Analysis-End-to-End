-- Creating a view for Default Rate
CREATE VIEW CHECK_DEFAULT AS
SELECT
    *,
    CASE
        WHEN LOAN_STATUS = 'DEFAULTED' THEN 1
        ELSE 0
    END AS IS_DEFAULT,
	
FROM SBA_DATA;

