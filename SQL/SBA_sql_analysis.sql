-- SBA TIME SERIES ANALYSIS

-- How has the SBA loan portfolio grown over the years?

SELECT
	YEAR(DISBURSEMENT_DATE_NEW) AS YEARS,
    COUNT(*) AS TOTAL_LOANS,
    SUM(LOAN_AMOUNT_DISBURSED) AS TOTAL_AMOUNT
FROM SBA_DATA
GROUP BY YEARS
ORDER BY TOTAL_LOANS DESC, TOTAL_AMOUNT DESC;



-- Year that recorded the highest default rate
-- OUT OF MINIMUM 100 LOANS
SELECT
	YEAR(DISBURSEMENT_DATE_NEW) AS MAX_DEFAULT_YEAR,
    ROUND(SUM(IS_DEFAULT)/COUNT(*)*100,2) AS DEFAULT_RATE
FROM CHECK_DEFAULT
GROUP BY MAX_DEFAULT_YEAR
HAVING COUNT(LOAN_ID) >= 100
ORDER BY DEFAULT_RATE DESC
LIMIT 5;


-- -- OUT OF MINIMUM 1000 LOANS
SELECT
	YEAR(DISBURSEMENT_DATE_NEW) AS MAX_DEFAULT_YEAR,
    ROUND(SUM(IS_DEFAULT)/COUNT(*)*100,2) AS DEFAULT_RATE
FROM CHECK_DEFAULT
GROUP BY MAX_DEFAULT_YEAR
HAVING COUNT(LOAN_ID) >= 1000
ORDER BY DEFAULT_RATE DESC
LIMIT 5;


-- Did the average loan amount changed over time?
-- Average Approved Loan
SELECT
	YEAR(APPROVAL_DATE_NEW) AS APPROVAL_DATE,
	ROUND(AVG(BANK_APPROVED_AMOUNT),2) as AVG_LOAN_AMOUNT
FROM SBA_DATA
GROUP BY YEAR(APPROVAL_DATE_NEW)
ORDER BY YEAR(APPROVAL_DATE_NEW);


-- Average Disbursed Loan

SELECT
	YEAR(DISBURSEMENT_DATE_NEW) AS DISBURSED_DATE,
	ROUND(AVG(LOAN_AMOUNT_DISBURSED),2) AS AVG_LOAN_AMOUNT
FROM SBA_DATA
GROUP BY YEAR(DISBURSEMENT_DATE_NEW)
ORDER BY YEAR(DISBURSEMENT_DATE_NEW);


-- sectors that dominated SBA lending every year

WITH RANKEDSECTORS AS (
    SELECT 
        YEAR(DISBURSEMENT_DATE_NEW) AS YEARS, 
        SECTOR, 
        COUNT(LOAN_ID) AS TOTAL_LOAN,
        RANK() OVER (
            PARTITION BY YEAR(DISBURSEMENT_DATE_NEW) 
            ORDER BY COUNT(LOAN_ID) DESC
        ) AS RANKINGY
    FROM SBA_DATA 
    WHERE SECTOR <> 'UNKNOWN INDUSTRY'
    GROUP BY YEAR(DISBURSEMENT_DATE_NEW), SECTOR
)
SELECT RANKINGY, YEARS, SECTOR, TOTAL_LOAN
FROM RANKEDSECTORS
WHERE RANKINGY <= 5 AND YEARS IS NOT NULL
ORDER BY YEARS ASC, RANKINGY ASC;


-- sector ranking by total loan amount


WITH RANKEDSECTORS AS (
    SELECT 
        YEAR(DISBURSEMENT_DATE_NEW) AS YEARS, 
        SECTOR, 
        SUM(LOAN_AMOUNT_DISBURSED) AS TOTAL_LOAN_AMOUNT,
        RANK() OVER (
            PARTITION BY YEAR(DISBURSEMENT_DATE_NEW) 
            ORDER BY SUM(LOAN_AMOUNT_DISBURSED) DESC
        ) AS RANKING_BY_AMOUNT
    FROM SBA_DATA 
    WHERE SECTOR <> 'UNKNOWN INDUSTRY'
    GROUP BY YEAR(DISBURSEMENT_DATE_NEW), SECTOR
)
SELECT RANKING_BY_AMOUNT, YEARS, SECTOR, TOTAL_LOAN_AMOUNT
FROM RANKEDSECTORS
WHERE RANKING_BY_AMOUNT <= 5 AND YEARS IS NOT NULL
ORDER BY YEARS ASC, RANKING_BY_AMOUNT ASC;



-- Which banks expanded their SBA lending the most over time?

WITH RANKED_BANK_TOTAL_LOANS AS (
	SELECT
		RANK() OVER(PARTITION BY YEAR(DISBURSEMENT_DATE_NEW) ORDER BY COUNT(LOAN_ID) DESC) AS BANK_RANKS,
        YEAR(DISBURSEMENT_DATE_NEW) AS YEARS,
        COUNT(LOAN_ID) AS TOTAL_LOANS_LENT,
        BANK_NAME
	FROM SBA_DATA
    GROUP BY YEARS, BANK_NAME
)
SELECT * FROM RANKED_BANK_TOTAL_LOANS
WHERE YEARS IS NOT NULL AND BANK_RANKS <= 10;


-- Which years had the highest portfolio losses and riskiest customer portfolio?

SELECT
	YEAR(DISBURSEMENT_DATE_NEW) AS YEARS,
    SUM(CHARGED_OFF_PRINCIPAL) AS DEFAULT_AMOUNT,
    ROUND((SUM(CHARGED_OFF_PRINCIPAL)/SUM(LOAN_AMOUNT_DISBURSED))*100,2) AS LOSS_RATE
FROM SBA_DATA
GROUP BY YEARS
ORDER BY LOSS_RATE DESC;


-- Has SBA guarantee percentage changed over time?

SELECT
	YEAR(DISBURSEMENT_DATE_NEW) AS YEARS,
    ROUND(AVG(SBA_PERCENT) * 100,2) AS Average_SBA_Coverage
FROM SBA_DATA
GROUP BY YEARS
ORDER BY YEARS ASC;


-- Did new businesses receive more loans over time?

SELECT 
	YEAR(DISBURSEMENT_DATE_NEW) AS YEARS,
    BUSINESS_TYPE,
    COUNT(LOAN_ID) AS TOTAL_LOANS
FROM SBA_DATA
WHERE BUSINESS_TYPE = 'NEW'
GROUP BY YEARS, BUSINESS_TYPE;



-- Which month has the highest loan approvals

SELECT
	MONTHNAME(APPROVAL_DATE_NEW) AS APPROVAL_MONTHS,
    COUNT(LOAN_ID) AS TOTAL_LOANS,
    SUM(LOAN_AMOUNT_DISBURSED) AS TOTAL_LOAN_AMOUNT,
    ROUND(SUM(IS_DEFAULT)/COUNT(*)*100,2) AS DEFAULT_RATE
FROM CHECK_DEFAULT
GROUP BY MONTHNAME(APPROVAL_DATE_NEW)
ORDER BY TOTAL_LOANS DESC	;



-- Before vs After Financial Crisis 2008

SELECT
	CASE
		WHEN YEAR(APPROVAL_DATE_NEW) > 2008 THEN 'AFTER FINANCIAL CRISIS'
        WHEN YEAR(APPROVAL_DATE_NEW) = 2008 THEN 'FINANCIAL CRISIS YEAR'
        ELSE 'BEFORE FINANCIAL CRISIS'
	END AS PERIOD,
    COUNT(LOAN_ID) AS TOTAL_LOANS,
    SUM(LOAN_AMOUNT_DISBURSED) AS TOTAL_LOAN_AMOUNT,
    AVG(LOAN_AMOUNT_DISBURSED) AS AVERAGE_LOAN_AMOUNT,
    ROUND(SUM(IS_DEFAULT)
            /
            COUNT(*)*100,2) AS DEFAULT_RATE,
	ROUND(SUM(CHARGED_OFF_PRINCIPAL)/SUM(LOAN_AMOUNT_DISBURSED)*100,2) AS LOSS_RATE,
    ROUND(AVG(SBA_PERCENT)*100,2) AS AVERAGE_SBA_PERCENT
FROM CHECK_DEFAULT
GROUP BY PERIOD;



