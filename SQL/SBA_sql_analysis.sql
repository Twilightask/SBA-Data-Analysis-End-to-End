-- Which employee_category sector wise has the most default rate

SELECT
    CONCAT(SECTOR, ' | ', EMPLOYEE_CATEGORY) AS COMPANY_INFO,
    COUNT(LOAN_ID) AS TOTAL_LOANS,
    SUM(IS_DEFAULT) AS TOTAL_DEFAULTED_LOANS,
    ROUND(
        SUM(IS_DEFAULT) / COUNT(LOAN_ID) * 100,
        2
    ) AS DEFAULT_RATE
FROM CHECK_DEFAULT
GROUP BY SECTOR, EMPLOYEE_CATEGORY
HAVING COUNT(LOAN_ID) > 1000
