-- Employee Risk Matrix
WITH EMPLOYEES_RISK AS(
SELECT
	EMPLOYEE_CATEGORY,
    ROUND(AVG(LOAN_AMOUNT_DISBURSED),2) AS AVERAGE_LOAN,
    ROUND(SUM(IS_DEFAULT)/COUNT(*)*100,2) AS DEFAULT_RATE,
	ROUND((SUM(CHARGED_OFF_PRINCIPAL)/SUM(LOAN_AMOUNT_DISBURSED))*100,2) AS LOSS_RATE
FROM CHECK_DEFAULT
GROUP BY EMPLOYEE_CATEGORY
),
SECOND_EMPLOYEES AS(
	SELECT 
		AVG(DEFAULT_RATE) AS AVERAGE_DEFAULTS,
        AVG(LOSS_RATE) AS AVERAGE_LOSS
	FROM EMPLOYEES_RISK
)
SELECT E.*,
	CASE 
		WHEN DEFAULT_RATE < AVERAGE_DEFAULTS AND LOSS_RATE < AVERAGE_LOSS THEN 'LOW RISK'
        WHEN DEFAULT_RATE > AVERAGE_DEFAULTS AND LOSS_RATE > AVERAGE_LOSS THEN 'HIGH RISK'
        ELSE 'MEDIUM RISK'
	END AS EMPLOYEE_RISK_CLASSIFICATION
FROM EMPLOYEES_RISK E
CROSS JOIN SECOND_EMPLOYEES
ORDER BY E.DEFAULT_RATE desc;



